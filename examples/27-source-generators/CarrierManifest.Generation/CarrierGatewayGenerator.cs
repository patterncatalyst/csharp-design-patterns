using System;
using System.Collections.Immutable;
using System.Text;
using System.Threading;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;

namespace System.Runtime.CompilerServices
{
    /// <summary>
    /// Polyfill required to use init-only properties and records when
    /// targeting netstandard2.0, whose BCL does not ship this marker type.
    /// The compiler only checks that the type exists, never its contents.
    /// </summary>
    internal static class IsExternalInit
    {
    }
}

namespace CarrierManifest.Generation
{
    /// <summary>
    /// One row of <c>carriers.manifest</c>: a carrier code, its display name,
    /// and the endpoint its gateway dispatches to.
    /// </summary>
    internal sealed record CarrierEntry(string Code, string DisplayName, string Endpoint);

    /// <summary>
    /// The whole parsed manifest, wrapped in <see cref="EquatableArray{T}"/>
    /// so the incremental pipeline can tell an unchanged manifest from a
    /// changed one by value instead of by array identity.
    /// </summary>
    internal readonly record struct CarrierManifestModel(EquatableArray<CarrierEntry> Entries);

    /// <summary>
    /// Reads <c>carriers.manifest</c> and emits one <see cref="CarrierManifest.ICarrierGateway"/>
    /// implementation per row, plus a <c>GeneratedCarrierRegistry</c> that
    /// lists and looks them up. Adding a carrier is a one-line data change in
    /// the manifest; no hand-written class is needed for it.
    /// </summary>
    [Generator(LanguageNames.CSharp)]
    public sealed class CarrierGatewayGenerator : IIncrementalGenerator
    {
        private const string ManifestExtension = ".manifest";

        public void Initialize(IncrementalGeneratorInitializationContext context)
        {
            var parsedManifests = context.AdditionalTextsProvider
                .Where(static file => file.Path.EndsWith(ManifestExtension, StringComparison.OrdinalIgnoreCase))
                .Select(static (text, cancellationToken) => Parse(text, cancellationToken))
                .WithTrackingName(TrackingNames.Parse);

            var model = parsedManifests.Collect()
                .Select(static (manifests, _) => Combine(manifests))
                .WithTrackingName(TrackingNames.Combine);

            context.RegisterSourceOutput(model, Emit);
        }

        private static CarrierManifestModel Parse(AdditionalText text, CancellationToken cancellationToken)
        {
            var sourceText = text.GetText(cancellationToken);
            if (sourceText is null)
            {
                return new CarrierManifestModel(ImmutableArray<CarrierEntry>.Empty);
            }

            var entries = ImmutableArray.CreateBuilder<CarrierEntry>();
            foreach (var line in sourceText.Lines)
            {
                var content = line.ToString();
                if (string.IsNullOrWhiteSpace(content))
                {
                    continue;
                }

                var parts = content.Split(',');
                if (parts.Length != 3)
                {
                    continue;
                }

                entries.Add(new CarrierEntry(parts[0].Trim(), parts[1].Trim(), parts[2].Trim()));
            }

            return new CarrierManifestModel(entries.ToImmutable());
        }

        private static CarrierManifestModel Combine(ImmutableArray<CarrierManifestModel> manifests)
        {
            if (manifests.IsDefaultOrEmpty)
            {
                return new CarrierManifestModel(ImmutableArray<CarrierEntry>.Empty);
            }

            var builder = ImmutableArray.CreateBuilder<CarrierEntry>();
            foreach (var manifest in manifests)
            {
                foreach (var entry in manifest.Entries)
                {
                    builder.Add(entry);
                }
            }

            return new CarrierManifestModel(builder.ToImmutable());
        }

        private static void Emit(SourceProductionContext context, CarrierManifestModel model)
        {
            if (model.Entries.Length == 0)
            {
                return;
            }

            var builder = new StringBuilder();
            builder.AppendLine("// <auto-generated/>");
            builder.AppendLine("#nullable enable");
            builder.AppendLine();
            // Explicit usings rather than relying on the consuming project's
            // ImplicitUsings: a generated file has to compile on its own
            // whether or not the consumer has that MSBuild feature turned on.
            builder.AppendLine("using System;");
            builder.AppendLine("using System.Collections.Generic;");
            builder.AppendLine();
            builder.AppendLine("namespace CarrierManifest;");
            builder.AppendLine();

            foreach (var entry in model.Entries)
            {
                builder.AppendLine($"public sealed class {entry.Code}CarrierGateway : ICarrierGateway");
                builder.AppendLine("{");
                builder.AppendLine($"    public string Code => \"{entry.Code}\";");
                builder.AppendLine();
                builder.AppendLine($"    public string DisplayName => \"{entry.DisplayName}\";");
                builder.AppendLine();
                builder.AppendLine($"    public string Endpoint => \"{entry.Endpoint}\";");
                builder.AppendLine("}");
                builder.AppendLine();
            }

            builder.AppendLine("public static class GeneratedCarrierRegistry");
            builder.AppendLine("{");
            builder.AppendLine("    public static IReadOnlyList<ICarrierGateway> All { get; } = new List<ICarrierGateway>");
            builder.AppendLine("    {");
            foreach (var entry in model.Entries)
            {
                builder.AppendLine($"        new {entry.Code}CarrierGateway(),");
            }

            builder.AppendLine("    };");
            builder.AppendLine();
            builder.AppendLine("    public static ICarrierGateway? Find(string code)");
            builder.AppendLine("    {");
            builder.AppendLine("        foreach (var gateway in All)");
            builder.AppendLine("        {");
            builder.AppendLine("            if (string.Equals(gateway.Code, code, StringComparison.Ordinal))");
            builder.AppendLine("            {");
            builder.AppendLine("                return gateway;");
            builder.AppendLine("            }");
            builder.AppendLine("        }");
            builder.AppendLine();
            builder.AppendLine("        return null;");
            builder.AppendLine("    }");
            builder.AppendLine("}");

            context.AddSource("GeneratedCarrierRegistry.g.cs", SourceText.From(builder.ToString(), Encoding.UTF8));
        }

        private static class TrackingNames
        {
            public const string Parse = "CarrierManifest.Parse";
            public const string Combine = "CarrierManifest.Combine";
        }
    }
}
